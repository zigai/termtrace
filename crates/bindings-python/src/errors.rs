/// Mutation facts present on every error; `None` unless the failed request reported them.
const MUTATION_FACTS: [&str; 5] = ["request_id", "details", "result", "step", "send_request_id"];
/// Detail attributes present on every locator failure; absent facts are `None`.
const LOCATOR_DETAILS: [&str; 10] = [
    "query",
    "state_hash",
    "frame_hash",
    "count",
    "ranges",
    "truncated",
    "index",
    "reason",
    "requested",
    "maximum",
];

/// Translate a `termtrace_sdk::Error` into an appropriate `PyErr`.
///
/// Every exception carries `kind` and `code`, `effect` (the model's mutation effect as a
/// dict), and `retry` (the retry rule the model derives from it).
pub fn to_py_err(err: termtrace_sdk::Error) -> PyErr {
    let msg = err.to_string();
    let kind = err.kind();
    let edit = err.edit_failure().cloned();
    let error = match kind {
        ErrorKind::StaleState => StateGuardFailedError::new_err(msg),
        ErrorKind::ControlTimeout => TimeoutError::new_err(msg),
        ErrorKind::ControlUnavailable => SessionNotFoundError::new_err(msg),
        ErrorKind::Evidence => IntegrityError::new_err(msg),
        ErrorKind::OriginalCaptureFailed => OriginalCaptureFailedError::new_err(msg),
        ErrorKind::OriginalFinalizationTimeout => OriginalFinalizationTimeoutError::new_err(msg),
        _ => TermtraceError::new_err(msg),
    };

    let original = matches!(
        kind,
        ErrorKind::OriginalCaptureFailed | ErrorKind::OriginalFinalizationTimeout
    );

    let error = typed_context(error, kind.as_str(), err.code(), err.failure_context());

    if let Some(failure) = edit {
        return attach(error, |py, value| {
            return value.setattr("details", to_python(py, &failure)?);
        });
    }

    if !original {
        return error;
    }

    // Capture facts are also exposed directly; `management` keeps the shared projection.
    return attach(error, |_py, value| {
        let facts = value.getattr("management")?.get_item("facts")?;
        for (attribute, field) in [
            ("completion", "completion"),
            ("reason", "reason"),
            ("evidence", "surviving"),
            ("capture_state", "state"),
            ("cleanup", "cleanup"),
        ] {
            value.setattr(attribute, facts.get_item(field)?)?;
        }

        return Ok(());
    });
}

/// Translate the failure of the mutation `request_id`.
///
/// Adds `request_id`, the actor's structured `details` (or `None`), and, for
/// `postcondition_incomplete`, the complete `result` whose input was applied.
pub fn mutation_err(err: termtrace_sdk::Error, request_id: Uuid) -> PyErr {
    let details = err.details().cloned();

    let incomplete = match &err {
        termtrace_sdk::Error::PostconditionIncomplete { result } => {
            Some(PyActionResult::new(Arc::new(result.as_ref().clone())))
        }
        _ => None,
    };

    let error = to_py_err(err);

    return attach(error, |py, value| {
        value.setattr("request_id", request_id.to_string())?;
        let details = match details {
            Some(details) => to_python(py, &details)?.unbind(),
            None => py.None(),
        };
        value.setattr("details", details)?;

        if let Some(result) = incomplete {
            value.setattr("result", result)?;
        }

        return Ok(());
    });
}

/// Translate a failed send step: the step's mutation error plus its zero-based `step` and the
/// whole send's `send_request_id`; `request_id` is the failed step's derived identity.
pub fn send_err(failure: SendFailure, send_request_id: Uuid) -> PyErr {
    let step = failure.step;
    let error = mutation_err(*failure.error, failure.request_id);

    return attach(error, |_py, value| {
        value.setattr("step", step)?;
        value.setattr("send_request_id", send_request_id.to_string())?;

        return Ok(());
    });
}

fn attach(
    error: PyErr,
    attributes: impl FnOnce(Python<'_>, &Bound<'_, PyBaseException>) -> PyResult<()>,
) -> PyErr {
    return Python::attach(|py| {
        let value = error.value(py).clone();

        return match attributes(py, &value) {
            Ok(()) => error,
            Err(failure) => {
                failure.set_cause(py, Some(error));
                failure
            }
        };
    });
}

/// A wait that ended without its condition holding; nothing was applied.
pub fn unsatisfied_wait(message: String) -> PyErr {
    return typed(
        TimeoutError::new_err(message),
        "wait_unsatisfied",
        "wait_unsatisfied",
        MutationEffect::NotApplied,
    );
}

/// Translate a pure query failure into `QueryError` with its typed details.
pub fn query_err(error: &termtrace_sdk::locator::QueryError) -> PyErr {
    return detailed(
        QueryError::new_err(error.to_string()),
        error.kind(),
        &LocatorFailure::Query(error.clone()),
        LastFrame::NotCarried,
    );
}

/// Translate a locator failure: capture failures keep their SDK error, timeouts raise
/// `LocatorTimeoutError` (a `TimeoutError`), cancellations raise `CancelledError`, and query
/// failures raise `QueryError`; timeouts and cancellations carry the last frame as `frame`.
pub fn locator_err(error: LocatorError) -> PyErr {
    let message = error.to_string();
    let kind = error.kind();
    let details = error.failure();

    return match error {
        LocatorError::Capture(capture) => to_py_err(capture),
        LocatorError::Timeout { frame, .. } => detailed(
            LocatorTimeoutError::new_err(message),
            kind,
            &details,
            LastFrame::Carried(frame),
        ),
        LocatorError::Cancelled { frame, .. } => detailed(
            CancelledError::new_err(message),
            kind,
            &details,
            LastFrame::Carried(frame),
        ),
        LocatorError::Query(_) => detailed(
            QueryError::new_err(message),
            kind,
            &details,
            LastFrame::NotCarried,
        ),
    };
}

enum LastFrame {
    NotCarried,
    Carried(Option<Arc<ScreenFrame>>),
}

fn detailed<T: serde::Serialize>(error: PyErr, kind: &str, details: &T, frame: LastFrame) -> PyErr {
    let error = typed(error, kind, kind, MutationEffect::NotApplied);

    return Python::attach(|py| {
        let value = error.value(py);
        let attached = to_python(py, details)
            .and_then(|details| {
                return LOCATOR_DETAILS.iter().try_for_each(|name| {
                    let detail = match details.cast::<pyo3::types::PyDict>() {
                        Ok(fields) => fields.get_item(*name)?,
                        Err(_) => None,
                    };

                    return value.setattr(*name, detail);
                });
            })
            .and_then(|()| {
                let LastFrame::Carried(frame) = frame else {
                    return Ok(());
                };
                let frame = match frame {
                    Some(frame) => PyFrame::new(frame).into_pyobject(py)?.into_any().unbind(),
                    None => py.None(),
                };

                return value.setattr("frame", frame);
            });

        return match attached {
            Ok(()) => error,
            Err(failure) => {
                failure.set_cause(py, Some(error));
                failure
            }
        };
    });
}

/// Attach `kind`, `code`, the model's `effect`, and its derived `retry` to an exception.
pub(crate) fn typed(error: PyErr, kind: &str, code: &str, effect: MutationEffect) -> PyErr {
    return typed_context(
        error,
        kind,
        code,
        termtrace_model::protocol::management::FailureContext::actor(effect),
    );
}

fn typed_context(
    error: PyErr,
    kind: &str,
    code: &str,
    context: termtrace_model::protocol::management::FailureContext,
) -> PyErr {
    use termtrace_model::protocol::management::FailureContext;
    return attach(error, |py, value| {
        value.setattr("kind", kind)?;
        value.setattr("code", code)?;

        match context {
            FailureContext::Actor { effect, retry } => {
                value.setattr("scope", "actor")?;
                value.setattr("effect", to_python(py, &effect)?)?;
                value.setattr("retry", to_python(py, &retry)?)?;
                value.setattr("management", py.None())?;
                value.setattr("guidance", py.None())?;
            }
            FailureContext::Management {
                guidance,
                management,
            } => {
                value.setattr("scope", "management")?;
                value.setattr("effect", py.None())?;
                value.setattr("retry", py.None())?;
                value.setattr("guidance", to_python(py, &guidance)?)?;
                value.setattr("management", to_python(py, &management)?)?;
            }
        }

        for name in MUTATION_FACTS {
            value.setattr(name, py.None())?;
        }

        return Ok(());
    });
}
