//! Write the Go model types, method stubs, and version from the server catalog.

use serde_json::Value;
use std::collections::{BTreeMap, BTreeSet};
use std::error::Error;
use std::fmt::Write as _;
use std::path::Path;
use std::result;
use termtrace_sdk::contracts::types::catalog as sdk_catalog;
use termtrace_sdk::contracts::types::declarations::{
    declarations, Declaration, DeclarationBody, Field, TypeExpr, WideInteger,
};
use termtrace_sdk_server::catalog::{catalog, MethodSchema};

const HEADER: &str = "// Code generated by `just generate` from the Termtrace SDK server catalog. DO NOT EDIT.\n\npackage termtrace\n";
const ERROR_DATA: &str = "ErrorData";
const INITIALISMS: [&str; 19] = [
    "api", "ascii", "cpu", "csi", "dpi", "fps", "gif", "html", "http", "id", "io", "json", "osc",
    "pid", "pty", "rgb", "url", "utf8", "uuid",
];

/// Declarations written by hand in `go/values.go`, by schema name, and the Go type they map to.
const HAND_WRITTEN: [(&str, &str); 5] = [
    ("ExactPath", "Path"),
    ("PathValue", "Path"),
    ("PathValueBase64", ""),
    ("DecimalU64", "DecimalU64"),
    ("DecimalU128", "DecimalU128"),
];

type Result<T> = result::Result<T, Box<dyn Error>>;

fn main() -> Result<()> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../go");
    let catalog = catalog()?;

    let sdk = sdk_catalog()?;
    let sdk_definitions = sdk
        .get("$defs")
        .and_then(Value::as_object)
        .ok_or("SDK catalog has no definitions")?;
    let sdk_names = declarations(
        sdk_definitions
            .iter()
            .map(|(name, schema)| return (name.clone(), schema)),
        &BTreeMap::new(),
    )?
    .into_keys()
    .collect::<BTreeSet<_>>();

    let mut roots = catalog
        .definitions
        .iter()
        .map(|(name, schema)| return (name.clone(), schema.clone()))
        .collect::<Vec<_>>();
    for (index, method) in catalog.methods.iter().enumerate() {
        roots.push((format!("MethodParams{index}"), method.params.clone()));
        roots.push((format!("MethodResult{index}"), method.result.clone()));
    }
    roots.push((format!("{ERROR_DATA}Root"), catalog.error_data.clone()));
    let mut declared = declarations(
        roots
            .iter()
            .map(|(name, schema)| return (name.clone(), schema)),
        &BTreeMap::new(),
    )?;

    let mut signatures = Vec::new();
    for (index, method) in catalog.methods.iter().enumerate() {
        let params = synthetic(&mut declared, &format!("MethodParams{index}"))?;
        let result = synthetic(&mut declared, &format!("MethodResult{index}"))?;
        signatures.push((method.clone(), params, result));
    }
    let error_data = synthetic(&mut declared, &format!("{ERROR_DATA}Root"))?;
    if error_data != TypeExpr::Named(ERROR_DATA.to_owned()) {
        return Err("error data is not the ErrorData definition".into());
    }

    let mut exported = sdk_names;
    let mut pending = signatures
        .iter()
        .map(|(_, _, result)| return result.clone())
        .chain([error_data])
        .collect::<Vec<_>>();
    while let Some(expr) = pending.pop() {
        for name in references(&expr) {
            if exported.insert(name.clone())
                && let Some(declaration) = declared.get(&name)
            {
                pending.extend(children(declaration));
            }
        }
    }

    let generator = Generator::new(&declared, &exported)?;
    let types = generator.types()?;
    let methods = generator.methods(&signatures)?;

    fs_err::write(root.join("types_gen.go"), types)?;
    fs_err::write(root.join("methods_gen.go"), methods)?;
    fs_err::write(
        root.join("version_gen.go"),
        format!(
            "{HEADER}\n// Version is the Termtrace release this module belongs to; the CLI must match it exactly.\nconst Version = \"{}\"\n",
            env!("CARGO_PKG_VERSION")
        ),
    )?;

    return Ok(());
}

fn synthetic(declared: &mut BTreeMap<String, Declaration>, name: &str) -> Result<TypeExpr> {
    return match declared
        .remove(name)
        .map(|declaration| return declaration.body)
    {
        Some(DeclarationBody::Alias(expr)) => Ok(expr),
        Some(DeclarationBody::Object { .. }) => {
            Err(format!("{name}: method params and results must be named types").into())
        }
        None => Err(format!("{name}: missing declaration").into()),
    };
}

fn references(expr: &TypeExpr) -> Vec<String> {
    return match expr {
        TypeExpr::Named(name) => vec![name.clone()],
        TypeExpr::Union(types) | TypeExpr::Tuple(types) => {
            types.iter().flat_map(references).collect()
        }
        TypeExpr::Array(item) | TypeExpr::Map(item) => references(item),
        _ => Vec::new(),
    };
}

fn children(declaration: &Declaration) -> Vec<TypeExpr> {
    return match &declaration.body {
        DeclarationBody::Object { fields, .. } => fields
            .iter()
            .map(|field| return field.value.clone())
            .collect(),
        DeclarationBody::Alias(expr) => vec![expr.clone()],
    };
}

fn pascal(text: &str) -> String {
    let mut out = String::new();
    for part in text
        .split(|character: char| return !character.is_ascii_alphanumeric())
        .filter(|part| return !part.is_empty())
    {
        let lower = part.to_ascii_lowercase();
        if INITIALISMS.contains(&lower.as_str()) {
            out.push_str(&lower.to_ascii_uppercase());
            continue;
        }
        let mut characters = part.chars();
        if let Some(first) = characters.next() {
            out.push(first.to_ascii_uppercase());
            out.extend(characters);
        }
    }
    if out.starts_with(|character: char| return character.is_ascii_digit()) {
        out.insert(0, 'V');
    }
    return out;
}

fn lower_first(text: &str) -> String {
    let mut characters = text.chars();
    return characters.next().map_or_else(String::new, |first| {
        return first.to_ascii_lowercase().to_string() + characters.as_str();
    });
}

fn comment(description: Option<&str>, indent: &str) -> String {
    let Some(text) = description
        .map(str::trim)
        .filter(|text| return !text.is_empty())
    else {
        return String::new();
    };
    let mut out = String::new();
    for line in text.lines() {
        let line = line.trim_end();
        if line.is_empty() {
            let _infallible = writeln!(out, "{indent}//");
        } else {
            let _infallible = writeln!(out, "{indent}// {line}");
        }
    }
    return out;
}

/// How the variants of a union are told apart.
enum Strategy {
    /// By the JSON text of one constant member every variant has.
    Tag(String),
    /// By the single member name of an externally tagged object.
    Key,
}

struct Union {
    strategy: Strategy,
    /// Leaf object declarations and the JSON text or member name that selects each.
    leaves: Vec<(String, String)>,
    /// Variants carried as bare strings, as serde writes unit variants of an externally tagged
    /// enum.
    units: Vec<String>,
}

struct Generator<'catalog> {
    declared: &'catalog BTreeMap<String, Declaration>,
    exported: &'catalog BTreeSet<String>,
    unions: BTreeMap<String, Union>,
    /// For each union, the unions that directly contain it.
    parents: BTreeMap<String, Vec<String>>,
    /// For each leaf object, the unions it belongs to.
    memberships: BTreeMap<String, BTreeSet<String>>,
}

impl<'catalog> Generator<'catalog> {
    fn new(
        declared: &'catalog BTreeMap<String, Declaration>,
        exported: &'catalog BTreeSet<String>,
    ) -> Result<Self> {
        let mut generator = Self {
            declared,
            exported,
            unions: BTreeMap::new(),
            parents: BTreeMap::new(),
            memberships: BTreeMap::new(),
        };

        for (name, declaration) in declared {
            if hand_written(name).is_some() {
                continue;
            }
            if let DeclarationBody::Alias(TypeExpr::Union(types)) = &declaration.body
                && generator.is_object_union(types)
            {
                let union = generator.union(name, types)?;
                for (leaf, _) in &union.leaves {
                    generator
                        .memberships
                        .entry(leaf.clone())
                        .or_default()
                        .insert(name.clone());
                }
                for member in types {
                    if let TypeExpr::Named(member) = member
                        && generator.is_union_alias(member)
                    {
                        generator
                            .parents
                            .entry(member.clone())
                            .or_default()
                            .push(name.clone());
                    }
                }
                generator.unions.insert(name.clone(), union);
            }
        }

        return Ok(generator);
    }

    fn is_union_alias(&self, name: &str) -> bool {
        return self.declared.get(name).is_some_and(|declaration| {
            return matches!(&declaration.body, DeclarationBody::Alias(TypeExpr::Union(types)) if self.is_object_union(types));
        });
    }

    fn is_object_union(&self, types: &[TypeExpr]) -> bool {
        return types
            .iter()
            .any(|member| return matches!(member, TypeExpr::Named(_)))
            && types.iter().all(|member| {
                if let TypeExpr::Literal(values) = member {
                    return values.iter().all(Value::is_string);
                }
                let TypeExpr::Named(name) = member else {
                    return false;
                };
                return matches!(
                    self.declared
                        .get(name)
                        .map(|declaration| return &declaration.body),
                    Some(DeclarationBody::Object { .. })
                ) || self.is_union_alias(name);
            });
    }

    fn leaves(&self, types: &[TypeExpr], out: &mut Vec<String>) {
        for member in types {
            let TypeExpr::Named(name) = member else {
                continue;
            };
            match self
                .declared
                .get(name)
                .map(|declaration| return &declaration.body)
            {
                Some(DeclarationBody::Alias(TypeExpr::Union(nested))) => self.leaves(nested, out),
                Some(_) if !out.contains(name) => out.push(name.clone()),
                Some(_) | None => {}
            }
        }
    }

    fn fields(&self, name: &str) -> &'catalog [Field] {
        return match self
            .declared
            .get(name)
            .map(|declaration| return &declaration.body)
        {
            Some(DeclarationBody::Object { fields, .. }) => fields,
            _ => &[],
        };
    }

    fn union(&self, name: &str, types: &[TypeExpr]) -> Result<Union> {
        let mut leaves = Vec::new();
        self.leaves(types, &mut leaves);
        let units = types
            .iter()
            .flat_map(|member| match member {
                TypeExpr::Literal(values) => {
                    return values
                        .iter()
                        .filter_map(|value| return value.as_str().map(str::to_owned))
                        .collect()
                }
                _ => return Vec::new(),
            })
            .collect::<Vec<_>>();

        let candidates = self
            .fields(leaves.first().map_or("", String::as_str))
            .iter()
            .filter(|field| return constant(field).is_some())
            .map(|field| return field.name.clone())
            .collect::<Vec<_>>();
        for tag in candidates.into_iter().filter(|_| return units.is_empty()) {
            let values = leaves
                .iter()
                .map(|leaf| {
                    return self
                        .fields(leaf)
                        .iter()
                        .find(|field| return field.name == tag)
                        .and_then(constant);
                })
                .collect::<Option<Vec<_>>>();
            if let Some(values) = values
                && values.iter().collect::<BTreeSet<_>>().len() == values.len()
            {
                return Ok(Union {
                    strategy: Strategy::Tag(tag),
                    leaves: leaves.into_iter().zip(values).collect(),
                    units,
                });
            }
        }

        let keys = leaves
            .iter()
            .map(|leaf| {
                return match self.fields(leaf) {
                    [only] if only.required => Some(only.name.clone()),
                    _ => None,
                };
            })
            .collect::<Option<Vec<_>>>();
        if let Some(keys) = keys
            && keys.iter().collect::<BTreeSet<_>>().len() == keys.len()
        {
            return Ok(Union {
                strategy: Strategy::Key,
                leaves: leaves.into_iter().zip(keys).collect(),
                units,
            });
        }

        return Err(
            format!("{name}: union variants have no shared constant or distinct key").into(),
        );
    }

    fn go_name(&self, name: &str) -> Result<String> {
        if let Some(mapped) = hand_written(name) {
            if mapped.is_empty() {
                return Err(format!("{name} is not usable from Go").into());
            }
            return Ok(mapped.to_owned());
        }
        let go = pascal(name);
        return Ok(if self.exported.contains(name) { go } else { lower_first(&go) });
    }

    fn is_reference_like(&self, expr: &TypeExpr) -> bool {
        return match expr {
            TypeExpr::Json | TypeExpr::Bytes | TypeExpr::Array(_) | TypeExpr::Map(_) => true,
            TypeExpr::Named(name) => {
                self.unions.contains_key(name)
                    || matches!(
                        self.declared.get(name).map(|declaration| return &declaration.body),
                        Some(DeclarationBody::Alias(alias)) if self.is_reference_like(alias)
                    )
            }
            _ => false,
        };
    }

    fn nullable(&self, expr: &TypeExpr) -> Result<String> {
        let rendered = self.render(expr)?;
        return Ok(
            if self.is_reference_like(expr) || rendered.starts_with('*') {
                rendered
            } else {
                format!("*{rendered}")
            },
        );
    }

    fn render(&self, expr: &TypeExpr) -> Result<String> {
        return Ok(match expr {
            TypeExpr::Json => "jsontext.Value".to_owned(),
            TypeExpr::Named(name) => self.go_name(name)?,
            TypeExpr::Path => "Path".to_owned(),
            TypeExpr::WideInteger(wide) => wide_integer(*wide)?,
            TypeExpr::Literal(values) => match values.first() {
                Some(Value::String(_)) => "string".to_owned(),
                Some(Value::Bool(_)) => "bool".to_owned(),
                Some(Value::Number(number)) if number.is_f64() => "float64".to_owned(),
                Some(Value::Number(_)) => "int".to_owned(),
                _ => return Err(format!("unsupported literal {values:?}").into()),
            },
            TypeExpr::Union(types) => {
                let present = types
                    .iter()
                    .filter(|member| return **member != TypeExpr::Null)
                    .collect::<Vec<_>>();
                match present.as_slice() {
                    [only] if present.len() < types.len() => self.nullable(only)?,
                    members
                        if members
                            .iter()
                            .all(|member| return matches!(member, TypeExpr::Literal(_))) =>
                    {
                        self.render(members.first().ok_or("empty union")?)?
                    }
                    _ => return Err(format!("unsupported inline union {types:?}").into()),
                }
            }
            TypeExpr::Boolean => "bool".to_owned(),
            TypeExpr::Integer => "int".to_owned(),
            TypeExpr::Number => "float64".to_owned(),
            TypeExpr::String => "string".to_owned(),
            TypeExpr::Bytes => "[]byte".to_owned(),
            TypeExpr::Array(item) => format!("[]{}", self.render(item)?),
            TypeExpr::Map(value) if **value == TypeExpr::Never => "struct{}".to_owned(),
            TypeExpr::Map(value) => format!("map[string]{}", self.render(value)?),
            TypeExpr::Tuple(items) => match items.as_slice() {
                [first, second] => {
                    format!("Pair[{}, {}]", self.render(first)?, self.render(second)?)
                }
                _ => return Err(format!("unsupported tuple {items:?}").into()),
            },
            TypeExpr::Never | TypeExpr::Null => {
                return Err(format!("unsupported type {expr:?}").into());
            }
        });
    }

    fn types(&self) -> Result<String> {
        let mut out = format!(
            "{HEADER}\nimport (\n\t\"encoding/json/v2\"\n\t\"encoding/json/jsontext\"\n)\n"
        );
        let mut decoders = Vec::new();

        for (name, declaration) in self.declared {
            if hand_written(name).is_some() {
                continue;
            }
            let go = self.go_name(name)?;
            out.push('\n');
            out.push_str(&comment(declaration.description.as_deref(), ""));

            match &declaration.body {
                DeclarationBody::Object { fields, frame } => {
                    out.push_str(&self.object(name, &go, fields, *frame)?);
                }
                DeclarationBody::Alias(TypeExpr::Union(types))
                    if self.unions.contains_key(name) =>
                {
                    out.push_str(&self.interface(name, &go, types)?);
                    decoders.push(self.decoder(name, &go)?);
                }
                DeclarationBody::Alias(expr) => out.push_str(&self.alias(&go, expr)?),
            }
        }

        out.push_str(
            "\nfunc init() {\n\tdecodeOptions = json.WithUnmarshalers(json.JoinUnmarshalers(\n",
        );
        for decoder in decoders {
            out.push_str(&decoder);
        }
        out.push_str("\t))\n}\n");

        return Ok(out);
    }

    /// Optional fields drop their Go zero value, so a field whose zero value is a real value other
    /// than its default becomes a pointer, and a field where null differs from absent becomes
    /// `Nullable`.
    fn field_type(&self, field: &Field) -> Result<String> {
        if field.explicit_null {
            let TypeExpr::Union(types) = &field.value else {
                return Err(format!("explicit-null field `{}` is not nullable", field.name).into());
            };
            let present = types
                .iter()
                .filter(|member| return **member != TypeExpr::Null)
                .collect::<Vec<_>>();
            let [only] = present.as_slice() else {
                return Err(
                    format!("explicit-null field `{}` has several types", field.name).into(),
                );
            };
            return Ok(format!("Nullable[{}]", self.render(only)?));
        }
        let rendered = self.render(&field.value)?;
        if field.required
            || !self.zero_is_value(&field.value)
            || field.default.as_ref().is_some_and(is_zero)
        {
            return Ok(rendered);
        }
        return Ok(format!("*{rendered}"));
    }

    fn zero_is_value(&self, expr: &TypeExpr) -> bool {
        return match expr {
            TypeExpr::Boolean
            | TypeExpr::Integer
            | TypeExpr::Number
            | TypeExpr::String
            | TypeExpr::WideInteger(_) => true,
            TypeExpr::Named(name) if !self.unions.contains_key(name) => matches!(
                self.declared.get(name).map(|declaration| return &declaration.body),
                Some(DeclarationBody::Alias(alias)) if self.zero_is_value(alias)
            ),
            _ => false,
        };
    }

    fn object(&self, name: &str, go: &str, fields: &[Field], frame: bool) -> Result<String> {
        let mut out = format!("type {go} struct {{\n");
        let mut constants = Vec::new();
        for field in fields {
            if let Some(value) = constant(field) {
                constants.push((field.name.clone(), value));
                continue;
            }
            let rendered = self.field_type(field)?;
            let (options, marker) =
                if field.required { ("", "") } else { (",omitzero", " //exhaustruct:optional") };
            out.push_str(&comment(field.description.as_deref(), "\t"));
            let _infallible = writeln!(
                out,
                "\t{} {rendered} `json:\"{}{options}\"`{marker}",
                pascal(&field.name),
                field.name
            );
        }
        if frame {
            out.push_str("\t// Frame is the exact frame these fields describe.\n\tFrame ScreenFrame `json:\"frame\"`\n");
        }
        out.push_str("}\n");

        for union in self.memberships.get(name).into_iter().flatten() {
            let _infallible = writeln!(out, "\nfunc ({go}) is{}() {{}}", pascal(union));
        }

        if !constants.is_empty() {
            let _infallible = write!(
                out,
                "\n// MarshalJSONTo writes the constant members alongside the fields.\nfunc (v {go}) MarshalJSONTo(enc *jsontext.Encoder) error {{\n\ttype plain {go}\n\treturn json.MarshalEncode(enc, struct {{\n"
            );
            for (index, (member, _)) in constants.iter().enumerate() {
                let _infallible =
                    writeln!(out, "\t\tConst{index} jsontext.Value `json:\"{member}\"`");
            }
            out.push_str("\t\tplain\n\t}{");
            for (_, value) in &constants {
                let _infallible = write!(out, "jsontext.Value(`{value}`), ");
            }
            out.push_str("plain(v)})\n}\n");
        }

        return Ok(out);
    }

    fn interface(&self, name: &str, go: &str, types: &[TypeExpr]) -> Result<String> {
        let mut out = format!("type {go} interface {{\n");
        for parent in self.parents.get(name).into_iter().flatten() {
            let _infallible = writeln!(out, "\t{}", self.go_name(parent)?);
        }
        let _infallible = writeln!(out, "\tis{}()", pascal(name));
        out.push_str("}\n");
        if types.is_empty() {
            return Err(format!("{name}: empty union").into());
        }

        let units = &self.unions.get(name).ok_or("missing union")?.units;
        if !units.is_empty() {
            let _infallible = write!(
                out,
                "\n// {go}Unit is a variant of {go} that carries no fields.\ntype {go}Unit string\n\nconst (\n"
            );
            for unit in units {
                let _infallible = writeln!(
                    out,
                    "\t{go}{} {go}Unit = {}",
                    pascal(unit),
                    serde_json::to_string(unit)?
                );
            }
            let _infallible = write!(out, ")\n\nfunc ({go}Unit) is{}() {{}}\n", pascal(name));
        }
        return Ok(out);
    }

    fn decoder(&self, name: &str, go: &str) -> Result<String> {
        let union = self.unions.get(name).ok_or("missing union")?;
        let mut out = format!(
            "\t\tjson.UnmarshalFromFunc(func(dec *jsontext.Decoder, v *{go}) error {{\n\t\t\traw, err := readUnion(dec)\n\t\t\tif raw == nil || err != nil {{\n\t\t\t\t*v = nil\n\t\t\t\treturn err\n\t\t\t}}\n"
        );
        if !union.units.is_empty() {
            let units = union
                .units
                .iter()
                .map(|unit| return serde_json::to_string(unit))
                .collect::<serde_json::Result<Vec<_>>>()?
                .join(", ");
            let _infallible = write!(
                out,
                "\t\t\tif unit, ok, unitErr := unionUnit(raw, {units}); ok || unitErr != nil {{\n\t\t\t\t*v = {go}Unit(unit)\n\t\t\t\treturn unitErr\n\t\t\t}}\n"
            );
        }
        match &union.strategy {
            Strategy::Tag(tag) => {
                let _infallible = writeln!(out, "\t\t\tselector, err := unionTag(raw, \"{tag}\")");
            }
            Strategy::Key => out.push_str("\t\t\tselector, err := unionKey(raw)\n"),
        }
        out.push_str(
            "\t\t\tif err != nil {\n\t\t\t\treturn err\n\t\t\t}\n\t\t\tswitch selector {\n",
        );
        for (leaf, selector) in &union.leaves {
            let selector = match union.strategy {
                Strategy::Tag(_) => selector.clone(),
                Strategy::Key => serde_json::to_string(selector)?,
            };
            let leaf = self.go_name(leaf)?;
            let _infallible = write!(
                out,
                "\t\t\tcase `{selector}`:\n\t\t\t\tvar leaf {leaf}\n\t\t\t\terr = json.Unmarshal(raw, &leaf, decodeOptions)\n\t\t\t\t*v = leaf\n"
            );
        }
        let _infallible = write!(
            out,
            "\t\t\tdefault:\n\t\t\t\treturn unknownVariant(\"{go}\", selector)\n\t\t\t}}\n\t\t\treturn err\n\t\t}}),\n"
        );
        return Ok(out);
    }

    fn alias(&self, go: &str, expr: &TypeExpr) -> Result<String> {
        let literals = match expr {
            TypeExpr::Literal(values) => Some(values.clone()),
            TypeExpr::Union(types)
                if types
                    .iter()
                    .all(|member| return matches!(member, TypeExpr::Literal(_))) =>
            {
                Some(
                    types
                        .iter()
                        .flat_map(|member| match member {
                            TypeExpr::Literal(values) => return values.clone(),
                            _ => return Vec::new(),
                        })
                        .collect(),
                )
            }
            _ => None,
        };

        if let Some(values) = literals
            && values.iter().all(Value::is_string)
        {
            let mut out = format!("type {go} string\n\nconst (\n");
            for value in values {
                let text = value.as_str().unwrap_or_default();
                let _infallible = writeln!(
                    out,
                    "\t{go}{} {go} = {}",
                    pascal(text),
                    serde_json::to_string(text)?
                );
            }
            out.push_str(")\n");
            return Ok(out);
        }

        return Ok(format!("type {go} = {}\n", self.render(expr)?));
    }

    fn methods(&self, signatures: &[(MethodSchema, TypeExpr, TypeExpr)]) -> Result<String> {
        let mut out = String::new();
        for (method, params, result) in signatures {
            let name = lower_first(&pascal(&method.name));
            let params = self.render(params)?;
            out.push('\n');
            out.push_str(&comment(Some(&method.description), ""));
            if *result == TypeExpr::Null {
                let _infallible = write!(
                    out,
                    "func (c *Client) {name}(ctx context.Context, params {params}) error {{\n\treturn callUnit(ctx, c, \"{}\", params)\n}}\n",
                    method.name
                );
            } else {
                let result = self.render(result)?;
                let _infallible = write!(
                    out,
                    "func (c *Client) {name}(ctx context.Context, params {params}) ({result}, error) {{\n\treturn call[{result}](ctx, c, \"{}\", params)\n}}\n",
                    method.name
                );
            }
        }
        let imports = if out.contains("jsontext.") {
            "import (\n\t\"context\"\n\t\"encoding/json/jsontext\"\n)\n"
        } else {
            "import \"context\"\n"
        };
        return Ok(format!("{HEADER}\n{imports}{out}"));
    }
}

fn hand_written(name: &str) -> Option<&'static str> {
    return HAND_WRITTEN
        .iter()
        .find(|(schema, _)| return *schema == name)
        .map(|(_, go)| return *go);
}

fn is_zero(value: &Value) -> bool {
    return match value {
        Value::Bool(flag) => !flag,
        Value::Number(number) => number.as_f64() == Some(0.0),
        Value::String(text) => text.is_empty(),
        Value::Null | Value::Array(_) | Value::Object(_) => false,
    };
}

fn constant(field: &Field) -> Option<String> {
    return match &field.value {
        TypeExpr::Literal(values) if values.len() == 1 => {
            values.first().map(|value| return value.to_string())
        }
        _ => None,
    };
}

fn wide_integer(wide: WideInteger) -> Result<String> {
    return Ok(match (wide.decimal_text, wide.bits, wide.signed) {
        (true, 64, false) => "DecimalU64".to_owned(),
        (true, 128, false) => "DecimalU128".to_owned(),
        (false, 64, true) => "int64".to_owned(),
        (false, 64, false) => "uint64".to_owned(),
        (false, 128, false) => "Uint128".to_owned(),
        _ => return Err(format!("unsupported wide integer {wide:?}").into()),
    });
}
