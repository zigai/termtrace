"""Generate strict internal msgspec models from the Rust driver schema."""

from __future__ import annotations

import os
import re
import subprocess
import tempfile
from pathlib import Path


PACKAGE_ROOT = Path(__file__).resolve().parents[1]
REPOSITORY_ROOT = PACKAGE_ROOT.parents[1]
GENERATED_ROOT = PACKAGE_ROOT / "src" / "termtrace" / "_generated"
MODELS = (
    ("driver-request.schema.json", "driver_request.py", False),
    ("driver-response.schema.json", "driver_response.py", True),
)


def main() -> None:
    """Regenerate the response model without timestamps or permissive structs."""

    for schema_name, output_name, add_aliases in MODELS:
        _generate(schema_name, output_name, add_aliases)


def _generate(schema_name: str, output_name: str, add_aliases: bool) -> None:
    schema = REPOSITORY_ROOT / "schemas" / schema_name
    output = GENERATED_ROOT / output_name
    with tempfile.TemporaryDirectory(prefix="termtrace-python-codegen-") as directory:
        generated = Path(directory) / output_name
        environment = os.environ.copy()
        environment["PYTHONWARNINGS"] = (
            "ignore::UserWarning:datamodel_code_generator.parser.jsonschema"
        )
        subprocess.run(
            [
                "datamodel-codegen",
                "--input",
                str(schema),
                "--input-file-type",
                "jsonschema",
                "--schema-version",
                "2020-12",
                "--schema-version-mode",
                "strict",
                "--output",
                str(generated),
                "--output-model-type",
                "msgspec.Struct",
                "--target-python-version",
                "3.11",
                "--use-standard-collections",
                "--use-union-operator",
                "--use-specialized-enum",
                "--disable-timestamp",
                "--formatters",
                "builtin",
            ],
            check=True,
            env=environment,
        )
        source = _normalize(generated.read_text(), schema_name, add_aliases)

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(source)


def _normalize(source: str, schema_name: str, add_aliases: bool) -> str:
    source = re.sub(
        r"# generated by datamodel-codegen:\n#   filename:  [^\n]+\n",
        f"# Generated from schemas/{schema_name}. DO NOT EDIT.\n",
        source,
    )
    source = re.sub(
        r"class (\w+)\(Struct([^)]*)\):",
        lambda match: (
            f"class {match.group(1)}(Struct, forbid_unknown_fields=True{match.group(2)}):"
        ),
        source,
    )
    if schema_name == "driver-request.schema.json":
        # msgspec cannot decode a union mixing string literals with two untagged
        # object variants. Rust still performs the exact NamedKey validation.
        source, replacements = re.subn(
            r"NamedKey: TypeAlias = .*",
            "NamedKey: TypeAlias = str | dict[str, int | str]",
            source,
        )
        if replacements != 1:
            raise RuntimeError("generated request model changed its NamedKey shape")
        source = source.replace(") = 'inherit'", ") = EnvironmentBase.inherit").replace(
            ") = 'auto'", ") = ColorPolicy.auto"
        )
        source = source.replace("Annotated, Literal, TypeAlias", "Annotated, TypeAlias")
        source = source.replace(
            "field(default_factory=list)",
            "field(default_factory=lambda: list[str]())",
            1,
        )
        source = source.replace(
            "field(default_factory=dict)",
            "field(default_factory=lambda: dict[str, Base64Bytes]())",
            1,
        )
        source = source.replace(
            "field(default_factory=list)",
            "field(default_factory=lambda: list[str]())",
            1,
        )
    if not add_aliases:
        return source
    aliases: list[str] = []
    alias_groups = {
        "DriverData": "Driver{tag}Data",
        "ControlData": "Control{tag}Data",
        "DriverResult": "Driver{tag}Result",
    }
    for class_prefix, alias_template in alias_groups.items():
        pattern = re.compile(
            rf"class ({class_prefix}\d+)\(Struct,[^\n]*tag='([^']+)'[^\n]*\):"
        )
        for class_name, tag in pattern.findall(source):
            pascal_tag = "".join(part.capitalize() for part in tag.split("_"))
            aliases.append(
                f"{alias_template.format(tag=pascal_tag)}: TypeAlias = {class_name}"
            )
    if not aliases:
        raise RuntimeError(
            "generated response models did not contain tagged driver variants"
        )
    return f"{source.rstrip()}\n\n# Stable names for anonymous tagged-union variants.\n{chr(10).join(aliases)}\n"


if __name__ == "__main__":
    main()
